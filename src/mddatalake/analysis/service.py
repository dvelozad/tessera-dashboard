"""Decide which obleas analyses a run supports, run them, and keep the results."""

from __future__ import annotations

import logging
import re
import tempfile
from pathlib import Path
from typing import Any

from mddatalake.analysis.obleas import AnalysisSeries, ObleasError, ObleasRunner
from mddatalake.core.config import settings

logger = logging.getLogger(__name__)

# Analyses that only need positions and a time base.
STRUCTURAL = ("density", "rdf")
TRANSPORT = ("diffusion",)

_LAMMPS_UNITS = re.compile(r"^\s*units\s+(\w+)", re.MULTILINE)


def detect_lammps_units(input_paths: list[Path]) -> str:
    """Find the ``units`` style declared by a LAMMPS input script."""
    for path in input_paths:
        try:
            text = Path(path).read_text(errors="replace")
        except OSError:
            continue
        match = _LAMMPS_UNITS.search(text)
        if match:
            return match.group(1).strip().lower()
    # LAMMPS requires a units declaration, so a missing one usually means the
    # input file was not among the artifacts; 'real' is the lab default.
    return "real"


def selections_from_mapping(atom_type_mapping: dict[str, Any] | None) -> dict[str, list[int]]:
    """Turn Tensor's atom type mapping into obleas ``select`` lines.

    The mapping looks like ``{"mappings": {"1": {"element": "O"}, ...}}``.
    """
    if not atom_type_mapping:
        return {}

    mappings = atom_type_mapping.get("mappings") or atom_type_mapping
    if not isinstance(mappings, dict):
        return {}

    by_element: dict[str, list[int]] = {}
    for type_id, info in mappings.items():
        try:
            type_number = int(type_id)
        except (TypeError, ValueError):
            continue

        if isinstance(info, str):
            element = info
        elif isinstance(info, dict):
            element = str(
                info.get("element") or info.get("name") or info.get("atom") or type_id
            )
        else:
            element = str(type_id)

        element = re.sub(r"[^A-Za-z0-9_]", "", element).strip() or f"t{type_number}"
        by_element.setdefault(element, []).append(type_number)

    return {name: sorted(types) for name, types in by_element.items()}


def types_from_data_file(path: Path) -> list[int]:
    """Read atom type ids from a LAMMPS data file's Masses section."""
    types: list[int] = []
    try:
        in_masses = False
        with open(path, "r", errors="replace") as handle:
            for _ in range(50000):
                line = handle.readline()
                if not line:
                    break
                stripped = line.strip()
                if not stripped:
                    if in_masses and types:
                        break
                    continue
                if stripped.split("#")[0].strip().lower() == "masses":
                    in_masses = True
                    continue
                if not in_masses:
                    continue
                parts = stripped.split()
                if len(parts) >= 2:
                    try:
                        types.append(int(parts[0]))
                    except ValueError:
                        continue
    except OSError as e:
        logger.warning(f"Could not read types from {path}: {e}")
    return sorted(set(types))


def build_lammps_config(
    *,
    trajectory: str,
    units: str,
    timestep: float | None,
    selections: dict[str, list[int]],
    label: str,
    with_transport: bool = True,
    lj_length_nm: float | None = None,
    lj_time_ps: float | None = None,
) -> str:
    """Generate the .anls config for a LAMMPS run."""
    lines = [
        "# generated by Tessera",
        f"trajectory {trajectory}",
        "trajectory_type lammps",
        f"lammps_units {units}",
    ]
    # Reduced units carry no intrinsic length or time; obleas refuses to guess,
    # so the σ/τ mapping the modeller chose is passed through.
    if units == "lj":
        if lj_length_nm and lj_time_ps:
            lines.append(f"lj_length_nm {lj_length_nm:g}")
            lines.append(f"lj_time_ps {lj_time_ps:g}")
        else:
            raise ObleasError(
                "Reduced (LJ) units need a length and time mapping: set "
                "lj_length_nm (σ in nm) and lj_time_ps (τ in ps) on the run."
            )
    if timestep:
        lines.append(f"timestep {timestep:g}")

    lines += [f"output_label {label}", "average_results true", ""]

    for name, types in selections.items():
        # obleas splits the value on commas; a space-separated list is a
        # syntax error ("unexpected token" at the second number).
        lines.append(f"select {name} type {','.join(str(t) for t in types)}")
    if selections:
        lines.append("")

    # Density requires an explicit selection, so it is only emitted when one
    # exists (every run with a readable data file gets an "all" selection).
    names = list(selections)
    if names:
        lines.append(f"analysis density 100 axis z kind number selection {names[0]}")
    if len(names) >= 2:
        lines.append(f"analysis rdf 200 ref {names[0]} sel {names[1]}")
    elif names:
        lines.append(f"analysis rdf 200 ref {names[0]} sel {names[0]}")

    if with_transport and timestep:
        lines.append("analysis diffusion")

    return "\n".join(lines) + "\n"


async def analyze_directory(
    directory: Path,
    metadata: dict[str, Any],
    runner: ObleasRunner,
    *,
    with_transport: bool = True,
    max_trajectory_bytes: int | None = None,
) -> list[AnalysisSeries]:
    """Run the analyses a run supports and return every series produced."""
    directory = Path(directory)
    engine = str(metadata.get("engine", "")).upper()
    series: list[AnalysisSeries] = []

    files = metadata.get("files", {})
    trajectories = _existing_paths(files.get("trajectories"))

    if engine == "GROMACS":
        from dataclasses import replace

        edrs = sorted(p for p in directory.glob("*.edr") if p.is_file())
        for edr in edrs:
            try:
                found = await runner.energy_from_edr(directory, edr)
            except ObleasError as e:
                logger.warning(f"obleas gmx energy failed for {edr.name}: {e}")
                continue

            # A staged run has one .edr per stage (em, nvt, npt_eq, npt_prod),
            # each with the same term names. Prefix with the stage so the
            # series stay distinguishable in the dashboard.
            if len(edrs) > 1:
                found = [replace(item, name=f"{edr.stem}/{item.name}") for item in found]
            series.extend(found)
        return series

    if engine != "LAMMPS" or not trajectories:
        return series

    trajectory = trajectories[0]
    if max_trajectory_bytes and trajectory.stat().st_size > max_trajectory_bytes:
        logger.info(
            f"Skipping obleas for {trajectory.name}: "
            f"{trajectory.stat().st_size} bytes exceeds the configured limit"
        )
        return series

    inputs = _existing_paths(files.get("input"))
    # The run's stored unit system wins; the input script is the fallback for
    # records made before it was recorded.
    from mddatalake.utils.units import normalise_units

    units = normalise_units(metadata.get("units")) or detect_lammps_units(inputs)
    lj_length_nm = metadata.get("lj_length_nm")
    lj_time_ps = metadata.get("lj_time_ps")
    data_files = _existing_paths(files.get("data"))
    selections = selections_from_mapping(metadata.get("atom_type_mapping"))

    if not selections and data_files:
        # No element mapping, but obleas still needs a selection; "all" over
        # the types declared by the data file is the honest choice.
        types = types_from_data_file(data_files[0])
        if types:
            selections = {"all": types}

    label = "tessera_" + re.sub(r"[^A-Za-z0-9_]", "_", directory.name)[:40]

    # obleas writes output/ next to the config, so work in a scratch directory
    # of symlinks rather than polluting the source run.
    with tempfile.TemporaryDirectory(prefix="tessera-obleas-") as tmp:
        work = Path(tmp)
        link = work / trajectory.name
        link.symlink_to(trajectory.resolve())

        for data in data_files[:1]:
            (work / data.name).symlink_to(data.resolve())

        config = build_lammps_config(
            trajectory=trajectory.name,
            units=units,
            timestep=_as_float(metadata.get("timestep")),
            selections=selections,
            label=label,
            with_transport=with_transport,
            lj_length_nm=_as_float(lj_length_nm),
            lj_time_ps=_as_float(lj_time_ps),
        )

        try:
            series = await runner.run_config(work, config)
        except ObleasError as e:
            # Transport analyses fail closed on Monte Carlo streams; retry with
            # the structural analyses only so rdf/density are still produced.
            logger.warning(f"obleas run failed, retrying structural only: {e}")
            try:
                structural = build_lammps_config(
                    trajectory=trajectory.name,
                    units=units,
                    timestep=_as_float(metadata.get("timestep")),
                    selections=selections,
                    label=label,
                    with_transport=False,
                    lj_length_nm=_as_float(lj_length_nm),
                    lj_time_ps=_as_float(lj_time_ps),
                )
                series = await runner.run_config(work, structural)
            except ObleasError as retry_error:
                logger.warning(f"obleas structural retry failed: {retry_error}")

    return series


def _existing_paths(value: Any) -> list[Path]:
    """Normalise a metadata file entry to a list of existing paths.

    The parsers are inconsistent here: ``trajectories`` is a list, while
    ``input`` and ``data`` are single strings. Iterating a string yields
    characters, which is how a one-character path such as ``/`` once reached
    the symlink code.
    """
    if not value:
        return []
    if isinstance(value, (str, Path)):
        value = [value]

    paths: list[Path] = []
    for item in value:
        path = Path(item)
        if path.exists():
            paths.append(path)
    return paths


def _as_float(value: Any) -> float | None:
    try:
        return float(value) if value is not None else None
    except (TypeError, ValueError):
        return None


def runner_from_settings() -> ObleasRunner:
    return ObleasRunner(
        binary=settings.obleas_bin,
        timeout=float(settings.obleas_timeout_seconds),
    )


async def store_series(db: Any, run_id: int, series: list[AnalysisSeries]) -> int:
    """Write analysis series as Observable rows for a run."""
    from mddatalake.db.models import Observable

    if not series:
        return 0

    created = 0
    for item in series:
        if len(item.y) < 2:
            continue

        values = item.y
        timeseries = {
            "timesteps": item.x,
            "values": values,
            "n_points": len(values),
            "x_label": item.x_name,
            "x_unit": item.x_unit,
            "source": item.source_file,
            "provider": "obleas",
        }
        db.add(
            Observable(
                simulation_run_id=run_id,
                observable_name=item.name,
                observable_type="timeseries",
                value_mean=sum(values) / len(values),
                value_std=_stdev(values),
                value_min=min(values),
                value_max=max(values),
                units=item.unit,
                timeseries_data=timeseries,
            )
        )
        created += 1
    return created


def _stdev(values: list[float]) -> float:
    if len(values) < 2:
        return 0.0
    mean = sum(values) / len(values)
    variance = sum((v - mean) ** 2 for v in values) / (len(values) - 1)
    return variance ** 0.5
